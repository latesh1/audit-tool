<?php

namespace App\Services\Extraction;

class ExtractedWebsiteData
{
    public function __construct(
        public readonly string $requestedUrl,
        public readonly string $finalUrl,
        public readonly int $httpStatus,
        public readonly int $responseTimeMs,
        public readonly bool $isHttps,
        public readonly ?string $title,
        public readonly int $titleLength,
        public readonly ?string $metaDescription,
        public readonly int $metaDescriptionLength,
        public readonly array $h1s,
        public readonly array $h2s,
        public readonly array $h3s,
        public readonly array $headingSequence,
        public readonly int $totalImages,
        public readonly int $imagesMissingAlt,
        public readonly int $imagesEmptyAlt,
        public readonly array $imageAltSamples,
        public readonly int $internalLinkCount,
        public readonly int $externalLinkCount,
        public readonly array $internalLinkSamples,
        public readonly array $externalLinkSamples,
        public readonly ?string $canonicalUrl,
        public readonly ?string $robotsMeta,
        public readonly ?string $viewportMeta,
        public readonly ?string $htmlLang,
        public readonly array $openGraph,
        public readonly array $twitterCard,
        public readonly bool $hasStructuredData,
        public readonly array $schemaTypes,
        public readonly int $wordCount,
        public readonly array $navigationItems,
        public readonly array $ctaCandidates,
        public readonly array $contactInfo,
        public readonly array $htmlLandmarks,
        public readonly array $duplicateIds,
        public readonly array $warnings = []
    ) {}

    public function toArray(): array
    {
        return [
            'requested_url' => $this->requestedUrl,
            'final_url' => $this->finalUrl,
            'http_status' => $this->httpStatus,
            'response_time_ms' => $this->responseTimeMs,
            'is_https' => $this->isHttps,
            'title' => $this->title,
            'title_length' => $this->titleLength,
            'meta_description' => $this->metaDescription,
            'meta_description_length' => $this->metaDescriptionLength,
            'h1_count' => count($this->h1s),
            'h1s' => $this->h1s,
            'h2_count' => count($this->h2s),
            'h2s' => $this->h2s,
            'h3_count' => count($this->h3s),
            'h3s' => $this->h3s,
            'heading_sequence' => $this->headingSequence,
            'total_images' => $this->totalImages,
            'images_missing_alt' => $this->imagesMissingAlt,
            'images_empty_alt' => $this->imagesEmptyAlt,
            'image_alt_samples' => $this->imageAltSamples,
            'internal_link_count' => $this->internalLinkCount,
            'external_link_count' => $this->externalLinkCount,
            'internal_link_samples' => $this->internalLinkSamples,
            'external_link_samples' => $this->externalLinkSamples,
            'canonical_url' => $this->canonicalUrl,
            'robots_meta' => $this->robotsMeta,
            'viewport_meta' => $this->viewportMeta,
            'html_lang' => $this->htmlLang,
            'open_graph' => $this->openGraph,
            'twitter_card' => $this->twitterCard,
            'has_structured_data' => $this->hasStructuredData,
            'schema_types' => $this->schemaTypes,
            'word_count' => $this->wordCount,
            'navigation_items' => $this->navigationItems,
            'cta_candidates' => $this->ctaCandidates,
            'contact_info' => $this->contactInfo,
            'html_landmarks' => $this->htmlLandmarks,
            'duplicate_ids' => $this->duplicateIds,
            'warnings' => $this->warnings,
        ];
    }
}
